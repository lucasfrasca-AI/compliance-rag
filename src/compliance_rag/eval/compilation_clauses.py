"""The whole compilation's selected clauses, exactly as the parser emits them,
committed for the recall gate (issue #180).

The gate's law corpus is the 779 clauses the selection manifest puts in scope,
not the 75-clause excerpt: production retrieves over all of them, and the
excerpt is an easier problem. The pinned compilation itself is a raw source
and is never committed (`.gitignore`: `corpus/instruments/**/raw/`), so CI
can't parse it. What is committed is the parser's output for the selected
clauses: `corpus/instruments/privacy-act-1988/C2026C00227/clauses.json`.

`scripts/export_compilation_clauses.py` is its only writer, from the pinned
bytes (sha256 checked). Nothing edits it by hand (CLAUDE.md, corpus rules:
parser output is never hand-edited). With the pinned source on disk,
`PRIVACY_ACT_COMPILATION_HTML` turns on the test that a fresh parse renders to
this file byte for byte; without it, CI still checks that every clause a
checked-in fixture also holds is that fixture's fresh parse, and that the
file's selection is the manifest's.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

from compliance_rag.corpus.models import ClauseRecord, incomplete_json, incomplete_of_json
from compliance_rag.corpus.parser import parse_compilation
from compliance_rag.corpus.selection_manifest import SelectionManifest, parse_selection_manifest

INSTRUMENT_VERSION_DIR = (
    Path(__file__).resolve().parents[3]
    / "corpus"
    / "instruments"
    / "privacy-act-1988"
    / "C2026C00227"
)
SELECTION_MANIFEST_PATH = INSTRUMENT_VERSION_DIR / "manifest.yaml"
COMPILATION_CLAUSES_PATH = INSTRUMENT_VERSION_DIR / "clauses.json"
WRITER = "scripts/export_compilation_clauses.py"


@dataclass(frozen=True, slots=True)
class CompilationClauses:
    """The committed file: what it was parsed from, and the clauses."""

    instrument_id: str
    version_id: str
    source_sha256: str
    """The pinned compilation's bytes (`SOURCE_SHA256` in `scripts/ingest_compilation.py`)."""
    selection: tuple[str, ...]
    """The manifest's prefixes the clauses were selected with."""
    clauses: tuple[ClauseRecord, ...]


def selection_manifest() -> SelectionManifest:
    return parse_selection_manifest(SELECTION_MANIFEST_PATH.read_text(encoding="utf-8"))


def select_compilation_clauses(
    source_html: str, *, instrument_id: str, version_id: str, selection: SelectionManifest
) -> tuple[ClauseRecord, ...]:
    """What ingest writes for this version (`corpus/ingest.py`): the parse,
    narrowed by the selection manifest, sorted by clause path."""
    parsed = parse_compilation(source_html, instrument_id=instrument_id, version_id=version_id)
    return selection.select(parsed.clauses)


def render_compilation_clauses(
    clauses: tuple[ClauseRecord, ...], *, source_sha256: str, selection: tuple[str, ...]
) -> str:
    """The file's exact text. One field per line, so a parser change shows in
    review as the clause text it changed."""
    if not clauses:
        raise ValueError("no clauses to render")
    first = clauses[0]
    for clause in clauses:
        if (clause.instrument_id, clause.version_id) != (first.instrument_id, first.version_id):
            raise ValueError(f"{clause.clause_id} is not {first.instrument_id}:{first.version_id}")
    document = {
        "note": f"Generated by {WRITER} from the pinned compilation. Never edit by hand: "
        "it is the parser's output for the clauses the selection manifest puts in scope.",
        "instrument_id": first.instrument_id,
        "version_id": first.version_id,
        "source_sha256": source_sha256,
        "selection": list(selection),
        "clause_count": len(clauses),
        "clauses": [_entry(c) for c in clauses],
    }
    return json.dumps(document, indent=1, ensure_ascii=False) + "\n"


def _entry(clause: ClauseRecord) -> dict[str, object]:
    entry: dict[str, object] = {
        "clause_path": clause.clause_path,
        "heading": clause.heading,
        "text": clause.text,
        "canonical_text": clause.canonical_text,
        "canonicalisation_version": clause.canonicalisation_version,
    }
    if clause.incomplete:
        # Only when there is one (ADR-0047), so the file shows the clauses
        # that are incomplete and nothing else changes.
        entry["incomplete"] = incomplete_json(clause.incomplete)
    return entry


def load_compilation_clauses(path: Path = COMPILATION_CLAUSES_PATH) -> CompilationClauses:
    # json.loads returns Any, so the three casts below name the shape the writer
    # renders. Nothing here trusts it: a missing key raises, str()/int() convert
    # each field, and ClauseRecord validates every record (canonical form, ids).
    raw = cast("dict[str, Any]", json.loads(path.read_text(encoding="utf-8")))
    instrument_id, version_id = str(raw["instrument_id"]), str(raw["version_id"])
    entries = cast("list[dict[str, Any]]", raw["clauses"])
    clauses = tuple(
        ClauseRecord(
            instrument_id=instrument_id,
            version_id=version_id,
            clause_path=str(entry["clause_path"]),
            heading=None if entry["heading"] is None else str(entry["heading"]),
            text=str(entry["text"]),
            canonical_text=str(entry["canonical_text"]),
            canonicalisation_version=int(entry["canonicalisation_version"]),
            incomplete=incomplete_of_json(entry.get("incomplete")),
        )
        for entry in entries
    )
    if len(clauses) != int(raw["clause_count"]):
        raise ValueError(f"{path}: {len(clauses)} clauses, header says {raw['clause_count']}")
    return CompilationClauses(
        instrument_id=instrument_id,
        version_id=version_id,
        source_sha256=str(raw["source_sha256"]),
        selection=tuple(str(p) for p in cast("list[Any]", raw["selection"])),
        clauses=clauses,
    )
